/**
 * Stroke-font glyph data, shared by every kernel variant of this project.
 *
 * Pure data plus metrics: no kernel types, no geometry. Each variant turns the
 * polylines into solids its own way (`text.ts` builds OCCT box prisms,
 * `text.replicad.ts` builds replicad ones), so the font itself is defined once.
 *
 * The kernels cannot share a real font here: OpenSCAD's `text()` goes through
 * fontconfig/FreeType, and the OCCT wasm build excludes `Font_BRepFont` (see
 * docs/research/occt-unbound-symbols-audit.md), so glyph outlines are not
 * available on that side. See docs/research/cad-text-and-custom-fonts.md for
 * what a real-font path costs and where it should live.
 */

